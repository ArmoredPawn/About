// Builds the land grid armies fight over: the map cut into cells 2.5 map pixels across (about 50 km), each one
// part of the province whose outline covers its centre. Provinces stay what the economy counts; the cells are
// the ground that changes hands as armies advance, so a front can run through the middle of a province.
//
//   npm run build:land   ->   public/js/engine/data/land.js

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { GEO, ORDER, MAP_SIZE } from '../public/js/engine/data/geo.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const CELL = 2.5;
const W = MAP_SIZE.w;
const H = MAP_SIZE.h;
const GW = Math.ceil(W / CELL);
const GH = Math.ceil(H / CELL);

const map = JSON.parse(readFileSync(path.join(ROOT, 'public/data/map.json'), 'utf8'));

// The province outlines are SVG paths of absolute moves, relative lines and closes
function rings(d) {
  const out = [];
  let ring = null;
  let x = 0;
  let y = 0;
  const tokens = d.match(/[MLlzZ]|-?\d*\.?\d+(?:e-?\d+)?/g) ?? [];
  let cmd = null;
  for (let i = 0; i < tokens.length;) {
    const t = tokens[i];
    if (/[MLlzZ]/.test(t)) {
      cmd = t;
      i++;
      if (cmd === 'z' || cmd === 'Z') { ring = null; cmd = null; }
      continue;
    }
    const a = Number(tokens[i]);
    const b = Number(tokens[i + 1]);
    i += 2;
    if (cmd === 'M') { x = a; y = b; ring = [[x, y]]; out.push(ring); cmd = 'l'; continue; }
    if (cmd === 'L') { x = a; y = b; } else { x += a; y += b; }
    if (!ring) { ring = [[x, y]]; out.push(ring); } else ring.push([x, y]);
  }
  return out;
}

const grid = new Int16Array(GW * GH).fill(-1);
ORDER.forEach((id, index) => {
  const d = map.regions[id];
  if (!d) return;
  const rs = rings(d).filter((r) => r.length >= 3);
  let minY = Infinity;
  let maxY = -Infinity;
  for (const r of rs) for (const [, py] of r) { if (py < minY) minY = py; if (py > maxY) maxY = py; }
  for (let gy = Math.max(0, Math.floor(minY / CELL)); gy <= Math.min(GH - 1, Math.ceil(maxY / CELL)); gy++) {
    const cy = gy * CELL + CELL / 2;
    const xs = [];
    for (const r of rs) {
      for (let i = 0; i < r.length; i++) {
        const [ax, ay] = r[i];
        const [bx, by] = r[(i + 1) % r.length];
        if ((ay <= cy && by > cy) || (by <= cy && ay > cy)) xs.push(ax + (cy - ay) / (by - ay) * (bx - ax));
      }
    }
    xs.sort((p, q) => p - q);
    for (let k = 0; k + 1 < xs.length; k += 2) {
      const g0 = Math.max(0, Math.ceil(xs[k] / CELL - 0.5));
      const g1 = Math.min(GW - 1, Math.floor(xs[k + 1] / CELL - 0.5));
      for (let gx = g0; gx <= g1; gx++) grid[gy * GW + gx] = index;
    }
  }
});

// Every province gets at least the cell under its centre (Singapore, Bahrain and the other small ones)
let tiny = 0;
const count = new Map();
for (const v of grid) if (v >= 0) count.set(v, (count.get(v) ?? 0) + 1);
ORDER.forEach((id, index) => {
  if (count.get(index)) return;
  const g = GEO[id];
  grid[Math.min(GH - 1, Math.floor(g.y / CELL)) * GW + Math.min(GW - 1, Math.floor(g.x / CELL))] = index;
  tiny++;
});

// Run-length encoded: value (province index + 1, 0 for sea) and run length, both base 36
const runs = [];
let prev = grid[0];
let n = 0;
for (const v of grid) {
  if (v === prev) { n++; continue; }
  runs.push(`${(prev + 1).toString(36)}.${n.toString(36)}`);
  prev = v;
  n = 1;
}
runs.push(`${(prev + 1).toString(36)}.${n.toString(36)}`);

const land = grid.reduce((t, v) => t + (v >= 0 ? 1 : 0), 0);
const out = `// Generated by scripts/build-land.js. Do not edit.
// The land grid: ${GW} x ${GH} cells of ${CELL} map pixels (about 50 km), ${land} of them land. Each run is
// "province index + 1 (0 = sea).run length", both base 36, provinces numbered as in geo.js ORDER.
export const LAND_GRID = { cell: ${CELL}, w: ${GW}, h: ${GH} };
export const LAND_RLE = '${runs.join(',')}';
`;
writeFileSync(path.join(ROOT, 'public/js/engine/data/land.js'), out);
console.log(`land.js: ${land} land cells, ${runs.length} runs, ${tiny} provinces given a single cell, ${(out.length / 1024).toFixed(0)} KB`);
